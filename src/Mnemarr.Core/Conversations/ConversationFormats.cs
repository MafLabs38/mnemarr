using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Mnemarr.Core.Conversations;

/// <summary>One thing said in a conversation: who said it, when (when the line says so), and the text.</summary>
public sealed record Turn(string Role, DateTimeOffset? At, string Text);

/// <summary>
/// The formats of conversation files that Mnemarr can read (ADR 0005, ADR 0024). The raw lines are kept as they were received; what is read out
/// of them is derived, and can be read again by a better reader. The format of an assistant's files is not a contract: a line that is not what
/// was expected is skipped, never a failure.
/// </summary>
public static partial class ConversationFormats
{
    /// <summary>The conversation files of Claude Code: one JSON object per line.</summary>
    public const string ClaudeCode = "claude-code";

    /// <summary>A turn longer than this is cut: a pasted file or a long answer is not what a memory is made of.</summary>
    public const int MaxTurnChars = 20_000;

    public static bool Supports(string format) => format == ClaudeCode;

    /// <summary>The turns of the lines, in order.</summary>
    public static IReadOnlyList<Turn> Turns(string format, IEnumerable<string> lines) =>
        format == ClaudeCode ? [.. lines.Select(ClaudeCodeTurn).OfType<Turn>()] : [];

    [GeneratedRegex(@"<(system-reminder|ide_[a-z_]+|local-command-[a-z]+|command-(?:name|message|args))>.*?</\1>", RegexOptions.Singleline | RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 2000)]
    private static partial Regex Noise();

    private static Turn? ClaudeCodeTurn(string line)
    {
        try
        {
            using var document = JsonDocument.Parse(line);
            var root = document.RootElement;
            if (root.ValueKind != JsonValueKind.Object || Flag(root, "isMeta") || Flag(root, "isSidechain"))
            {
                return null;
            }

            var role = Text(root, "type");
            if (role is not ("user" or "assistant") || !root.TryGetProperty("message", out var message) || message.ValueKind != JsonValueKind.Object || !message.TryGetProperty("content", out var content))
            {
                return null;
            }

            // The line was masked as it is written in JSON; what it says once decoded (an escape such as \u0067) is masked too, before it reaches the note, the title or the index.
            var text = Clean(SecretMasker.Mask(ContentText(content)), role);
            return text.Length == 0 ? null : new Turn(role, At(root), CutTurn(text));
        }
        catch (Exception ex) when (ex is JsonException or RegexMatchTimeoutException)
        {
            // A line that is not JSON (a file cut in the middle, another version of the format): there is nothing to take from it.
            return null;
        }
    }

    private static string ContentText(JsonElement content)
    {
        if (content.ValueKind == JsonValueKind.String)
        {
            return content.GetString() ?? string.Empty;
        }

        if (content.ValueKind != JsonValueKind.Array)
        {
            return string.Empty;
        }

        // Only what was said: the calls of tools, their results and the thinking are not the conversation, and are the bulk of it.
        var parts = content.EnumerateArray().Where(block => block.ValueKind == JsonValueKind.Object && Text(block, "type") == "text").Select(block => Text(block, "text")).Where(text => !string.IsNullOrWhiteSpace(text));
        return string.Join("\n\n", parts);
    }

    private static string Clean(string text, string role)
    {
        var cleaned = role == "user" ? Noise().Replace(text, string.Empty).Trim() : text.Trim();
        return cleaned.StartsWith("Caveat: The messages below were generated by the user while running local commands", StringComparison.Ordinal) ? string.Empty : cleaned;
    }

    private static string CutTurn(string text) => text.Length <= MaxTurnChars ? text : text[..MaxTurnChars] + "\n… [cut]";

    private static bool Flag(JsonElement element, string name) => element.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.True;

    private static string Text(JsonElement element, string name) => element.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.String ? value.GetString() ?? string.Empty : string.Empty;

    private static DateTimeOffset? At(JsonElement root) =>
        DateTimeOffset.TryParse(Text(root, "timestamp"), CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal, out var at) ? at.ToUniversalTime() : null;
}

/// <summary>A conversation as a note: front matter that says where it comes from, a title taken from what was first asked, and each turn under its own heading.</summary>
public static class ConversationMarkdown
{
    private const int MaxTitle = 80;
    /// <summary>A sentence says something when it is at least this long and has at least this many words (a greeting, an "ok", a "go on" are short, in any language).</summary>
    private const int MinTitle = 8;

    private const int MinWords = 3;

    private static readonly Regex Fence = new(@"```.*?```", RegexOptions.Singleline | RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));
    private static readonly Regex Address = new(@"https?://\S+", RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));
    private static readonly Regex Sentence = new(@"[^.?!\n]+[.?!]?", RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));

    /// <summary>The whole note of a conversation: its header, then each turn.</summary>
    public static string Render(string format, string machine, string application, string session, DateTimeOffset startedAt, IReadOnlyList<Turn> turns) =>
        Header(format, machine, application, session, startedAt, turns) + Sections(turns);

    /// <summary>The front matter that says where a conversation comes from, and its title (from its first turns).</summary>
    public static string Header(string format, string machine, string application, string session, DateTimeOffset startedAt, IReadOnlyList<Turn> turns)
    {
        var text = new StringBuilder();
        text.Append("---\n")
            .Append(CultureInfo.InvariantCulture, $"tags: [conversation, {application}]\n")
            .Append(CultureInfo.InvariantCulture, $"source: {format}\nmachine: {machine}\napplication: {application}\nsession: {session}\n")
            .Append(CultureInfo.InvariantCulture, $"started: {startedAt.ToUniversalTime():yyyy-MM-ddTHH:mm:ssZ}\n---\n")
            .Append("# ").Append(Title(turns, session)).Append("\n\n");
        return text.ToString();
    }

    /// <summary>The turns, each under its own heading, to be added to the end of a note.</summary>
    public static string Sections(IReadOnlyList<Turn> turns)
    {
        var text = new StringBuilder();
        foreach (var turn in turns)
        {
            var who = turn.Role == "user" ? "User" : "Assistant";
            var when = turn.At is { } at ? string.Create(CultureInfo.InvariantCulture, $" · {at:yyyy-MM-dd HH:mm}") : string.Empty;
            text.Append("## ").Append(who).Append(when).Append("\n\n").Append(Fenced(turn.Text)).Append("\n\n");
        }

        return text.ToString();
    }

    /// <summary>The name of the file of a conversation: in the folder of the machine it was held on, then of the application, named from the day it began and its session (the whole of it: two sessions never share a file).</summary>
    public static string NotePath(string machine, string application, DateTimeOffset startedAt, string session) =>
        string.Create(CultureInfo.InvariantCulture, $"{machine}/{application}/{startedAt.ToUniversalTime():yyyy-MM-dd}-{session}.md");

    /// <summary>
    /// A title drawn from what was asked, when no model was asked to summarise the conversation: the first thing a person said that says
    /// something (not a short greeting or acknowledgement, not a code block, not an address), as its first sentence.
    /// </summary>
    public static string Title(IReadOnlyList<Turn> turns, string session)
    {
        foreach (var turn in turns.Where(turn => turn.Role == "user").Take(6))
        {
            var sentence = FirstSentence(turn.Text);
            if (sentence.Length >= MinTitle)
            {
                return CutTitle(sentence);
            }
        }

        var first = turns.FirstOrDefault(turn => turn.Role == "user")?.Text ?? string.Empty;
        var line = OneLine(first.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).FirstOrDefault() ?? string.Empty);
        return line.Length == 0 ? $"Conversation {session[..Math.Min(8, session.Length)]}" : CutTitle(line);
    }

    private static string FirstSentence(string text)
    {
        try
        {
            var plain = Address.Replace(Fence.Replace(text, " "), " ");
            foreach (Match match in Sentence.Matches(plain))
            {
                var sentence = OneLine(match.Value);
                if (sentence.Length >= MinTitle && sentence.Split(' ', StringSplitOptions.RemoveEmptyEntries).Length >= MinWords)
                {
                    return sentence;
                }
            }
        }
        catch (RegexMatchTimeoutException)
        {
            // A text that cannot be read quickly is not a good title: the next turn, or the plain first line, will do.
        }

        return string.Empty;
    }

    /// <summary>One line, with no run of spaces and nothing that Markdown would read as a link, a tag or a heading: a title is said by someone else.</summary>
    private static string OneLine(string text) =>
        string.Join(' ', text.Replace("[", string.Empty, StringComparison.Ordinal).Replace("]", string.Empty, StringComparison.Ordinal).Replace("#", string.Empty, StringComparison.Ordinal).Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries)).Trim(' ', '"', '\'', '`');

    private static string CutTitle(string line) => line.Length <= MaxTitle ? line : line[..MaxTitle].TrimEnd() + "…";

    /// <summary>
    /// The text in a code fence longer than any run of backticks inside it: a conversation is said by someone else, and what it contains (headings,
    /// <c>[[links]]</c>, <c>#tags</c>) must not become the structure, the links or the tags of the note. A fence says nothing to the reader of links.
    /// </summary>
    private static string Fenced(string text)
    {
        var longest = 0;
        var run = 0;
        foreach (var c in text)
        {
            run = c == '`' ? run + 1 : 0;
            longest = Math.Max(longest, run);
        }

        var fence = new string('`', Math.Max(3, longest + 1));
        return $"{fence}text\n{text}\n{fence}";
    }
}
